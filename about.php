        const cards = document.querySelectorAll('.approach-cards');

        cards.forEach(card => {
            card.addEventListener('mousemove', e => {
                const rect = card.getBoundingClientRect();
                const x = e.clientX - rect.left;
                const y = e.clientY - rect.top;
                const centerX = rect.width / 2;
                const centerY = rect.height / 2;
                const rotateX = (y - centerY) / 10;
                const rotateY = (centerX - x) / 10;

                card.style.transform = `rotateX(${rotateX}deg) rotateY(${rotateY}deg)`;

                const xPercent = (x / rect.width) * 100;
                const yPercent = (y / rect.height) * 100;
                card.style.setProperty('--x', `${xPercent}%`);
                card.style.setProperty('--y', `${yPercent}%`);
            });

            card.addEventListener('mouseleave', () => {
                card.style.transform = 'rotateX(0deg) rotateY(0deg)';
            });
        });
    </script>

    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const counterElement = document.getElementById('counter');
            const counterSection = document.getElementById('counterSection');
            let hasAnimated = false;

            // Format number with leading zero
            function formatNumber(num) {
                return num < 10 ? '0' + num : num;
            }

            // Check if element is in viewport
            function isInViewport(element) {
                const rect = element.getBoundingClientRect();
                return (
                    rect.top >= 0 &&
                    rect.top <= (window.innerHeight || document.documentElement.clientHeight)
                );
            }

            // Animate counter
            function animateCounter() {
                if (!hasAnimated && isInViewport(counterSection)) {
                    hasAnimated = true;
                    let count = 1;

                    const interval = setInterval(() => {
                        counterElement.textContent = formatNumber(count);

                        // Change color to orange when reaching 7
                        if (count === 7) {
                            counterElement.style.color = 'orange';
                        }

                        count++;
                        if (count > 7) {
                            clearInterval(interval);
                        }
                    }, 300); // Speed of animation (300ms between each number)
                }
            }

            // Check on scroll
            window.addEventListener('scroll', animateCounter);

            // Check on initial load
            animateCounter();
        });
    </script>
    <script>
        document.addEventListener("DOMContentLoaded", function() {
            const imgSection = document.querySelector(".founder-img-section");
            const imgContainer = document.querySelector(".founder-img-container");
            const content = document.querySelector(".founder-content");
            const image = document.querySelector(".founder-img");

            // Set initial height for the container to match content
            imgContainer.style.height = content.offsetHeight + "px";

            function onScroll() {
                const scrollY = window.scrollY;
                const containerRect = imgContainer.getBoundingClientRect();
                const containerTop = containerRect.top + scrollY;
                const containerHeight = imgContainer.offsetHeight;
                const imageHeight = image.offsetHeight;

                // Calculate the boundaries for sticky behavior
                const stickyStart = containerTop;
                const stickyEnd = containerTop + containerHeight - imageHeight;

                // Apply the appropriate positioning
                if (scrollY >= stickyStart && scrollY <= stickyEnd) {
                    // Sticky phase - image follows the scroll
                    imgSection.style.position = "fixed";
                    imgSection.style.top = "20px";
                    imgSection.style.width = imgContainer.offsetWidth + "px";
                } else if (scrollY > stickyEnd) {
                    // Past the sticky end - image stays at the bottom of container
                    imgSection.style.position = "absolute";
                    imgSection.style.top = (containerHeight - imageHeight) + "px";
                    imgSection.style.width = "100%";
                } else {
                    // Before the sticky start - image stays at the top of container
                    imgSection.style.position = "absolute";
                    imgSection.style.top = "0";
                    imgSection.style.width = "100%";
                }
            }

            // Update on scroll and resize
            window.addEventListener("scroll", onScroll);
            window.addEventListener("resize", function() {
                // Update container height on resize
                imgContainer.style.height = content.offsetHeight + "px";
                onScroll();
            });

            // Initial call to set positions
            onScroll();
        });
    </script>

